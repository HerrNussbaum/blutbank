import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {CardSearch as S} from '../dist/card-search.mjs';
const cards=JSON.parse(readFileSync(new URL('../dist/data/cards.json',import.meta.url)));
const fixture={name:'Überwächter',set:'Origin',group:'Test',notes:'Official errata',text:{types:['Character'],colors:['green'],subtypes:['Elf'],rarity:'K',keywords:['Flying'],rulesText:'Flying. Draw a card.',stats:{asp:0,pow:3,hp:null,level:2},mechanics:{pool:true,binding:null}}};
assert(S.matches(fixture,{q:'uberwachter flying'}));
assert(S.matches(fixture,{q:'"draw a card" asp<=4 pow>=3'}));
assert(!S.matches(fixture,{q:'"draw two cards"'}));
assert(S.matches(fixture,{q:'grün charakter'}),'German property aliases');
assert(S.matches(fixture,{aspMin:'0',aspMax:'0'}),'Printed zero is a real value');
assert(!S.matches(fixture,{hpMax:'2'}),'Unknown HP must not match a numeric filter');
assert(!S.matches(fixture,{q:'hp=0'}),'Unknown HP must not be treated as zero');
assert(S.matches(fixture,{unknown:'hp'}));
assert(!S.matches(fixture,{color:'black'}));
assert(S.matches(fixture,{set:'Origin',type:'Character',subtype:'Elf',color:'green',rarity:'K',mechanic:'pool',levelMin:'2',levelMax:'2'}));
assert(!S.matches(fixture,{mechanic:'binding'}));
assert(!S.matches(fixture,{aspMax:'-1'}));
assert(!S.matches(fixture,{aspMin:'not-a-number'}));
assert(S.matches(fixture,{}),'Reset includes all cards');
assert(S.query(fixture,'errata'),'Official notes are searchable');
const ids=new Set(cards.map(c=>c.id));
for(const c of cards){
 assert(c.text?.rawText,`Missing complete OCR: ${c.id}`);
 assert(c.text.source===c.original,`Wrong image provenance: ${c.id}`);
 assert(['machine','reviewed'].includes(c.text.status));
 for(const k of S.numeric)assert(c.text.stats[k]===null||c.text.stats[k]==='X'||Number.isInteger(c.text.stats[k]),`Invalid ${k}: ${c.id}`);
 assert(S.matches(c,{}));
}
const amazon=cards.find(c=>c.id==='4bee77b4f168');
assert(S.matches(amazon,{type:'Character',color:'white',aspMin:'4',aspMax:'4',powMin:'2',powMax:'2',hpMin:'3',hpMax:'3'}));
assert(!S.matches(amazon,{aspMax:'3'}));
const tobin=cards.find(c=>c.id==='9d7645b2b87e');
assert(tobin.text.types.includes('Character')&&tobin.text.traits.includes('Advisor'));
assert.equal(tobin.text.stats.hp,null,'Advisor has no printed HP');
assert(S.matches(tobin,{mechanic:'pool'}));
const rune=cards.find(c=>c.id==='83ffeed6cc65');
assert(rune.text.types.includes('Rune')&&rune.text.types.includes('Resource'));
const exports=JSON.parse(readFileSync(new URL('../dist/data/card-texts.json',import.meta.url)));
assert.equal(exports.length,cards.length);assert(exports.every(c=>ids.has(c.id)));
console.log(`Card search: ${cards.length} complete text records, numeric/range, language, AND and unknown-value checks passed.`);
